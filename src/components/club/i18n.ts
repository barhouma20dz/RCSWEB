const dict = { ar, fr, en }

export type TKey = keyof typeof ar

// ==================== المخزن ====================
export function applyDir(lang: Lang) {
  if (typeof document === 'undefined') return
  document.documentElement.lang = lang
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
}

interface I18nState {
  lang: Lang
  setLang: (lang: Lang) => void
}

export const useLang = create<I18nState>()(
  persist(
    (set) => ({
      lang: 'ar',
      setLang: (lang) => {
        set({ lang })
        applyDir(lang)
      },
    }),
    // skipHydration: نعيد الترطيب يدوياً بعد التحميل لتجنب اختلاف الترطيب بين الخادم والمتصفح
    { name: 'raed-lang', skipHydration: true }
  )
)

/** دالة الترجمة: t('key') */
export function useT() {
  const lang = useLang((s) => s.lang)
  return (key: TKey): string => dict[lang][key] ?? dict.ar[key] ?? key
}
